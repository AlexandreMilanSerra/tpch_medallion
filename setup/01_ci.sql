-- Run once as ACCOUNTADMIN. Creates what GitHub Actions needs to run dbt build.
USE ROLE ACCOUNTADMIN;

-- Separate role and database: CI never touches TPCH_DEMO
CREATE ROLE IF NOT EXISTS DBT_CI_ROLE;
CREATE DATABASE IF NOT EXISTS TPCH_CI;
GRANT OWNERSHIP ON DATABASE TPCH_CI TO ROLE DBT_CI_ROLE COPY CURRENT GRANTS;
GRANT USAGE ON WAREHOUSE DBT_WH TO ROLE DBT_CI_ROLE;
GRANT IMPORTED PRIVILEGES ON DATABASE SNOWFLAKE_SAMPLE_DATA TO ROLE DBT_CI_ROLE;

-- Service user with key-pair authentication (no password, no MFA prompt)
CREATE USER IF NOT EXISTS <CI_USER>
  TYPE = SERVICE
  DEFAULT_ROLE = DBT_CI_ROLE
  DEFAULT_WAREHOUSE = DBT_WH
  RSA_PUBLIC_KEY = '<PASTE_PUBLIC_KEY_HERE>';
GRANT ROLE DBT_CI_ROLE TO USER <CI_USER>;
