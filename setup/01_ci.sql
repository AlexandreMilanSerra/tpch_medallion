-- 01_ci.sql
-- CI environment: separate database, limited role and a key-pair service user.
-- Run as ACCOUNTADMIN. The public key is not secret, but never put the PRIVATE key
-- in the repository.

USE ROLE ACCOUNTADMIN;

CREATE DATABASE IF NOT EXISTS TPCH_CI;
CREATE ROLE IF NOT EXISTS DBT_CI_ROLE;

GRANT USAGE, OPERATE ON WAREHOUSE DBT_WH TO ROLE DBT_CI_ROLE;
GRANT IMPORTED PRIVILEGES ON DATABASE SNOWFLAKE_SAMPLE_DATA TO ROLE DBT_CI_ROLE;
GRANT ALL ON DATABASE TPCH_CI TO ROLE DBT_CI_ROLE;
GRANT ALL ON FUTURE SCHEMAS IN DATABASE TPCH_CI TO ROLE DBT_CI_ROLE;

CREATE USER IF NOT EXISTS DBT_CI_USER
  TYPE = SERVICE
  DEFAULT_ROLE = DBT_CI_ROLE
  DEFAULT_WAREHOUSE = DBT_WH
  RSA_PUBLIC_KEY = '<paste the public key here, without header lines>';

GRANT ROLE DBT_CI_ROLE TO USER DBT_CI_USER;