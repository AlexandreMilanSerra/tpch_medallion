-- Run once as ACCOUNTADMIN / DBT_ROLE after the first dbt build (tags must exist).
-- 1. ACCOUNTADMIN
GRANT APPLY MASKING POLICY ON ACCOUNT TO ROLE DBT_ROLE;

-- 2. DBT_ROLE (owner of the GOVERNANCE schema and the PII tag)
CREATE MASKING POLICY TPCH_DEMO.GOVERNANCE.MASK_PII
  AS (val STRING) RETURNS STRING ->
  CASE
    WHEN CURRENT_ROLE() IN ('DBT_ROLE', 'ACCOUNTADMIN') THEN val
    ELSE '*** MASKED ***'
  END;

ALTER TAG TPCH_DEMO.GOVERNANCE.PII
  SET MASKING POLICY TPCH_DEMO.GOVERNANCE.MASK_PII;

-- 3. ACCOUNTADMIN: demo analyst role
CREATE ROLE ANALYST_ROLE;
GRANT USAGE ON WAREHOUSE DBT_WH TO ROLE ANALYST_ROLE;
GRANT USAGE ON DATABASE TPCH_DEMO TO ROLE ANALYST_ROLE;
GRANT USAGE ON SCHEMA TPCH_DEMO.SILVER TO ROLE ANALYST_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA TPCH_DEMO.SILVER TO ROLE ANALYST_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA TPCH_DEMO.SILVER TO ROLE ANALYST_ROLE;
